#define FONT_FIRST_CHAR 0x20
#define FONT_LAST_CHAR  0x7E

void gfx_clear(uint8_t *fb)
{
    memset(fb, 0xFF, EPD_FB_SIZE); // 1 = white
}

/**
 * @brief Set one pixel in panel RAM coordinates. No transform, no clipping
 *        beyond the framebuffer itself.
 */
static void plot(uint8_t *fb, int px, int py, bool black)
{
    uint8_t *byte = &fb[py * EPD_ROW_BYTES + px / 8];
    const uint8_t mask = 0x80u >> (px & 7); // MSB is the leftmost RAM column

    if (black) {
        *byte &= (uint8_t)~mask;
    } else {
        *byte |= mask;
    }
}

/*
 * Canvas -> panel. See the orientation block in gfx.h for what each step is
 * correcting. With the shipped settings (landscape, mirrored, clockwise) the
 * two steps collapse into a transpose -- the mirror undoes half the rotation
 * -- but they are written out separately so either can be changed on its own.
 */
void gfx_pixel(uint8_t *fb, int x, int y, bool black)
{
    if (x < 0 || x >= GFX_W || y < 0 || y >= GFX_H) {
        return;
    }

#if GFX_LANDSCAPE
#if GFX_ROTATE_CW
    int px = (GFX_H - 1) - y;
    int py = x;
#else
    int px = y;
    int py = (GFX_W - 1) - x;
#endif
#else
    int px = x;
    int py = y;
#endif

#if GFX_MIRROR_X
    px = (EPD_WIDTH - 1) - px;
#endif

    plot(fb, px, py, black);
}

void gfx_fill_rect(uint8_t *fb, int x, int y, int w, int h, bool black)
{
    for (int row = y; row < y + h; row++) {
        for (int col = x; col < x + w; col++) {
            gfx_pixel(fb, col, row, black);
        }
    }
}

void gfx_hline(uint8_t *fb, int x, int y, int w, bool black)
{
    gfx_fill_rect(fb, x, y, w, 1, black);
}

int gfx_text_width(const char *s, int scale)
{
    const int n = (int)strlen(s);
    if (n == 0) {
        return 0;
    }

    // Every glyph advances GFX_ADVANCE, but the last one's trailing gap is not
    // part of the visible width.
    return (n * GFX_ADVANCE - 1) * scale;
}

static void gfx_char(uint8_t *fb, int x, int y, char c, int scale, bool black)
{
    if (c < FONT_FIRST_CHAR || c > FONT_LAST_CHAR) {
        return; // unrepresentable, leave the cell blank
    }

    const uint8_t *glyph = FONT5X7[(unsigned char)c - FONT_FIRST_CHAR];

    for (int col = 0; col < GFX_FONT_W; col++) {
        for (int row = 0; row < GFX_FONT_H; row++) {
            if (!(glyph[col] & (1u << row))) {
                continue;
            }
            if (scale == 1) {
                gfx_pixel(fb, x + col, y + row, black);
            } else {
                gfx_fill_rect(fb, x + col * scale, y + row * scale, scale, scale, black);
            }
        }
    }
}

int gfx_text(uint8_t *fb, int x, int y, const char *s, int scale, bool black)
{
    if (scale < 1) {
        scale = 1;
    }

    for (; *s; s++) {
        gfx_char(fb, x, y, *s, scale, black);
        x += GFX_ADVANCE * scale;
    }

    return x;
}

int gfx_text_center(uint8_t *fb, int y, const char *s, int scale, bool black)
{
    return gfx_text(fb, (GFX_W - gfx_text_width(s, scale)) / 2, y, s, scale, black);
}

int gfx_text_right(uint8_t *fb, int right_x, int y, const char *s, int scale, bool black)
{
    return gfx_text(fb, right_x - gfx_text_width(s, scale), y, s, scale, black);
}
